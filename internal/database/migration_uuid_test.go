// The two created_at values the seeded notes use: the first note is the oldest, the second and the
// third share one, so the down migration has a tie to break with the rowid.
var (
	noteTimeFirst = time.Date(2024, 1, 1, 9, 30, 0, 0, time.UTC)
	noteTimeTie   = time.Date(2024, 2, 1, 9, 30, 0, 0, time.UTC)
)

// storedNote is a note read back after the up migration, when its id is a UUID string.
type storedNote struct {
	ID        string    `db:"id"`
	Title     string    `db:"title"`
	Body      string    `db:"body"`
	CreatedAt time.Time `db:"created_at"`
	Status    int       `db:"status"`
}

// integerNote is a note read back after the down migration, when its id is an integer again.
type integerNote struct {
	ID        int64     `db:"id"`
	Title     string    `db:"title"`
	Body      string    `db:"body"`
	CreatedAt time.Time `db:"created_at"`
	Status    int       `db:"status"`
}

// openVersionThree returns a database whose schema is at version 3, the version migration 000004
// upgrades from: the first pass of migrateUp applies exactly the files below 000004.
func openVersionThree(t *testing.T) *sqlx.DB {
	t.Helper()
	db, err := sqlx.Open("sqlite", MemoryDSN)
	require.NoError(t, err)
	db.SetMaxOpenConns(1)
	t.Cleanup(func() { _ = db.Close() })

	_, err = db.Exec("PRAGMA foreign_keys = ON")
	require.NoError(t, err)

	files, err := migrationsBeforeNotesUUID()
	require.NoError(t, err)
	m, err := newMigrator(db, files)
	require.NoError(t, err)
	require.NoError(t, m.Up())

	var version int
	require.NoError(t, db.Get(&version, "SELECT version FROM schema_migrations"))
	require.Equal(t, 3, version)
	return db
}

// seedVersionThreeNotes stores two notes with integer ids plus a third one that carries a tag, so
// the migration has titles, bodies, created_at values, statuses and a link to carry across.
func seedVersionThreeNotes(t *testing.T, db *sqlx.DB) {
	t.Helper()
	for _, note := range []struct {
		id        int64
		title     string
		body      string
		createdAt time.Time
		status    int
	}{
		{1, "first", "a", noteTimeFirst, 1},
		{2, "second", "b", noteTimeTie, 0},
		{3, "third", "c", noteTimeTie, 2},
	} {
		_, err := db.Exec(
			"INSERT INTO notes (id, title, body, created_at, status) VALUES (?, ?, ?, ?, ?)",
			note.id, note.title, note.body, note.createdAt, note.status)
		require.NoError(t, err)
	}
	_, err := db.Exec("INSERT INTO tags (name) VALUES ('go')")
	require.NoError(t, err)
	_, err = db.Exec("INSERT INTO note_tags (note_id, tag_id) VALUES (3, 1)")
	require.NoError(t, err)
}

// TestNotesUUIDMigrationKeepsExistingNotes upgrades a version-3 database holding notes and a tag
// link: every note keeps its title, body, created_at and status, gets its own canonical lowercase
// UUID, and the link still points at the note it belonged to.
func TestNotesUUIDMigrationKeepsExistingNotes(t *testing.T) {
	db := openVersionThree(t)
	seedVersionThreeNotes(t, db)

	require.NoError(t, migrateUp(db))

	var version int
	require.NoError(t, db.Get(&version, "SELECT version FROM schema_migrations"))
	assert.Equal(t, 4, version, "the database reached the UUID migration")

	var notes []storedNote
	require.NoError(t, db.Select(&notes, "SELECT id, title, body, created_at, status FROM notes"))
	require.Len(t, notes, 3, "no note was lost")

	want := map[string]storedNote{
		"first":  {Title: "first", Body: "a", CreatedAt: noteTimeFirst, Status: 1},
		"second": {Title: "second", Body: "b", CreatedAt: noteTimeTie, Status: 0},
		"third":  {Title: "third", Body: "c", CreatedAt: noteTimeTie, Status: 2},
	}
	ids := make(map[string]struct{}, len(notes))
	for _, note := range notes {
		wantNote, ok := want[note.Title]
		require.True(t, ok, "unexpected note %q", note.Title)
		// The UUID is generated by the migration, so it is checked for its form rather than
		// against a fixed value; everything else is the note that was stored before it.
		assert.Equal(t, wantNote.Body, note.Body, note.Title)
		assert.Equal(t, wantNote.Status, note.Status, note.Title)
		assert.True(t, wantNote.CreatedAt.Equal(note.CreatedAt), "%s keeps its created_at", note.Title)

		parsed, err := uuid.Parse(note.ID)
		require.NoError(t, err, "the new id of %s is a UUID", note.Title)
		assert.Equal(t, note.ID, parsed.String(), "the id of %s is in canonical form", note.Title)
		assert.Equal(t, uuid.Version(4), parsed.Version(), "the id of %s is a UUID v4", note.Title)
		ids[note.ID] = struct{}{}
	}
	assert.Len(t, ids, 3, "every note gets its own UUID")

	// The tag link followed the note it belonged to, which is now named by its UUID.
	var thirdID string
	require.NoError(t, db.Get(&thirdID, "SELECT id FROM notes WHERE title = 'third'"))
	var links int
	require.NoError(t, db.Get(&links, "SELECT COUNT(*) FROM note_tags WHERE note_id = ? AND tag_id = 1", thirdID))
	assert.Equal(t, 1, links, "the link still points at the note it belonged to")

	var total int
	require.NoError(t, db.Get(&total, "SELECT COUNT(*) FROM note_tags"))
	assert.Equal(t, 1, total, "no link was dropped or duplicated")
}

// TestNotesUUIDMigrationIsReversible runs the down migration after the up one: the integer ids come
// back as 1..N in created_at order with the rowid breaking the tie, the note content is unchanged
// and every link still points at the same note.
func TestNotesUUIDMigrationIsReversible(t *testing.T) {
	db := openVersionThree(t)
	seedVersionThreeNotes(t, db)
	require.NoError(t, migrateUp(db))

	down, err := migrationsFS.ReadFile("migrations/000004_notes_uuid.down.sql")
	require.NoError(t, err)
	_, err = db.Exec(string(down))
	require.NoError(t, err)

	var notes []integerNote
	require.NoError(t, db.Select(&notes, "SELECT id, title, body, created_at, status FROM notes ORDER BY id"))
	require.Len(t, notes, 3, "no note was lost")

	want := []integerNote{
		{ID: 1, Title: "first", Body: "a", CreatedAt: noteTimeFirst, Status: 1},
		{ID: 2, Title: "second", Body: "b", CreatedAt: noteTimeTie, Status: 0},
		{ID: 3, Title: "third", Body: "c", CreatedAt: noteTimeTie, Status: 2},
	}
	for i, wantNote := range want {
		got := notes[i]
		assert.Equal(t, wantNote.ID, got.ID, "the ids are 1..N in created_at order with the rowid breaking ties")
		assert.Equal(t, wantNote.Title, got.Title, "note %d keeps its title", wantNote.ID)
		assert.Equal(t, wantNote.Body, got.Body, "note %d keeps its body", wantNote.ID)
		assert.Equal(t, wantNote.Status, got.Status, "note %d keeps its status", wantNote.ID)
		assert.True(t, wantNote.CreatedAt.Equal(got.CreatedAt), "note %d keeps its created_at", wantNote.ID)
	}

	// The third note was the tagged one while the ids were UUIDs, and it is the third one again.
	var links int
	require.NoError(t, db.Get(&links, "SELECT COUNT(*) FROM note_tags WHERE note_id = 3 AND tag_id = 1"))
	assert.Equal(t, 1, links, "the link still points at the note it belonged to")

	var total int
	require.NoError(t, db.Get(&total, "SELECT COUNT(*) FROM note_tags"))
	assert.Equal(t, 1, total, "no link was dropped or duplicated")
}

// TestOpenIsIdempotentAtVersionFour opens a fresh database, which is already at version 4, and then
// runs the migrations again: the stored note is left exactly as it was.
func TestOpenIsIdempotentAtVersionFour(t *testing.T) {
	db, err := Open(MemoryDSN)
	require.NoError(t, err)
	t.Cleanup(func() { _ = db.Close() })

	createdAt := time.Date(2024, 3, 1, 12, 0, 0, 0, time.UTC)
	_, err = db.Exec(
		"INSERT INTO notes (id, title, body, created_at, status) VALUES (?, 'kept', 'b', ?, 1)",
		testNoteID, createdAt)
	require.NoError(t, err)

	var before []storedNote
	require.NoError(t, db.Select(&before, "SELECT id, title, body, created_at, status FROM notes"))

	require.NoError(t, migrateUp(db))

	var after []storedNote
	require.NoError(t, db.Select(&after, "SELECT id, title, body, created_at, status FROM notes"))
	require.Len(t, after, 1, "the note is still there")
	assert.Equal(t, before[0].ID, after[0].ID, "the id does not change")
	assert.Equal(t, before[0].Title, after[0].Title, "the title does not change")
	assert.Equal(t, before[0].Body, after[0].Body, "the body does not change")
	assert.Equal(t, before[0].Status, after[0].Status, "the status does not change")
	assert.True(t, before[0].CreatedAt.Equal(after[0].CreatedAt), "created_at does not change")

	var version int
	require.NoError(t, db.Get(&version, "SELECT version FROM schema_migrations"))
	assert.Equal(t, 4, version, "the database stays at the UUID migration")
}
